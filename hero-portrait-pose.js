// Normalized image coordinates measured from the top left of the portrait.
export const portraitEye = Object.freeze({ x: 0.532, y: 0.269 });

// Pass the portrait video's currentTime. Positive roll is clockwise on screen, in radians.
export function portraitPoseAt(seconds) {
  const last = samples.length / 4 - 1;
  const time = Number.isFinite(seconds) ? seconds : 0;
  const frame = Math.min(last, Math.max(0, time * framesPerSecond - firstSampleFrame));
  const index = Math.floor(frame);
  const progress = frame - index;
  const start = index * 4;
  const end = Math.min(last, index + 1) * 4;
  const at = (column) => (samples[start + column] + (samples[end + column] - samples[start + column]) * progress) / precision;
  return { x: portraitEye.x + at(0), y: portraitEye.y + at(1), scale: 1 + at(2), roll: at(3) };
}
